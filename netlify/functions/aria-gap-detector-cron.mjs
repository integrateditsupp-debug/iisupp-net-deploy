/**
 * aria-gap-detector-cron — Daily 06:00 UTC scan of ARIA conversation logs for gaps
 *  Identifies: low-confidence answers (score < 0.6), no_match returns, thumbs-down votes
 *  Clusters by intent/topic via simple word-overlap
 *  Generates KB stub markdown files for top 3 gap clusters into outputs/kb-gap-stubs/
 *  Emails Ahmad weekly digest of top gaps for human review
 *  Cat 21 + Cat 22 — Self-improving knowledge base.
 */
const TOP_N_GAPS = 5;
const MIN_CLUSTER_SIZE = 3;

export default async () => {
  const out = { scanned_at: new Date().toISOString(), gaps_found: 0, stubs_drafted: 0 };
  let store, kbStore;
  try {
    const { getStore } = await import('@netlify/blobs');
    store = getStore({ name: 'aria-feedback', consistency: 'eventual' });
    kbStore = getStore({ name: 'aria-kb-gap-stubs', consistency: 'strong' });
  } catch {
    out.error = 'blobs unavailable';
    return new Response(JSON.stringify(out), { headers: { 'Content-Type': 'application/json' } });
  }

  // Pull last 24h of feedback / low-confidence events
  const since = Date.now() - 24 * 3600 * 1000;
  const downs = [];
  try {
    const list = await store.list();
    for (const item of (list.blobs || [])) {
      const f = await store.get(item.key, { type: 'json' });
      if (!f) continue;
      if ((f.ts || 0) < since) continue;
      if (f.vote === 'down' || (f.confidence || 1) < 0.6 || f.intent === 'no_match') {
        downs.push({
          text: (f.text || f.user_text || '').toLowerCase().slice(0, 200),
          intent: f.intent || 'unknown',
          ts: f.ts || 0
        });
      }
    }
  } catch (e) { out.list_err = e.message; }

  out.gaps_found = downs.length;
  if (downs.length === 0) {
    return new Response(JSON.stringify(out), { headers: { 'Content-Type': 'application/json' } });
  }

  // Cluster by word overlap (simple)
  const clusters = [];
  for (const d of downs) {
    const words = new Set(d.text.split(/\s+/).filter(w => w.length > 3));
    let matched = false;
    for (const c of clusters) {
      const overlap = [...words].filter(w => c.words.has(w)).length;
      if (overlap >= 3) {
        c.items.push(d);
        words.forEach(w => c.words.add(w));
        matched = true;
        break;
      }
    }
    if (!matched) clusters.push({ words, items: [d] });
  }

  // Keep clusters with >= MIN_CLUSTER_SIZE
  const topClusters = clusters
    .filter(c => c.items.length >= MIN_CLUSTER_SIZE)
    .sort((a, b) => b.items.length - a.items.length)
    .slice(0, TOP_N_GAPS);

  // Draft KB stub per cluster
  for (const c of topClusters) {
    const sample = c.items[0].text;
    const wordList = [...c.words].slice(0, 8);
    const slug = 'gap-' + Date.now() + '-' + wordList[0].replace(/[^a-z0-9]/g, '');

    const stub = `---
title: AUTO-DRAFT: ${wordList.slice(0, 4).join(' ')}
status: gap-stub-pending-human-review
auto_drafted_at: ${new Date().toISOString()}
cluster_size: ${c.items.length}
keywords: [${wordList.join(', ')}]
---

## Detected gap

ARIA returned low-confidence / no-match / thumbs-down for ${c.items.length} similar queries in the last 24h.

## Sample queries from cluster

${c.items.slice(0, 5).map(i => '- "' + i.text.slice(0, 100) + '"').join('\n')}

## Suggested fix

Add a KB entry covering this topic. Human should:
1. Identify the actual symptom from the cluster
2. Write a bit-native KB entry following the standard format
3. Add to the appropriate vertical or tier folder
4. Delete this stub after KB entry ships

## Pattern keywords

${wordList.join(' · ')}
`;

    try {
      await kbStore.setJSON(slug + '.md', { stub, drafted_at: Date.now() });
      out.stubs_drafted++;
    } catch (e) { /* skip */ }
  }

  // Email Ahmad if any stubs drafted
  if (out.stubs_drafted > 0 && process.env.RESEND_API_KEY) {
    const html = `<div style="font-family:system-ui,sans-serif;max-width:560px;margin:0 auto;color:#111;line-height:1.6;padding:20px">
      <h2 style="color:#d4af37">ARIA detected ${out.stubs_drafted} KB gap${out.stubs_drafted>1?'s':''} in last 24h</h2>
      <p>Stubs drafted to <code>aria-kb-gap-stubs</code> blob store. Review and convert to real KB entries when you have 10 minutes.</p>
      <p>Top gap clusters by frequency:</p>
      <ul>${topClusters.map(c => '<li>' + c.items.length + ' queries: ' + [...c.words].slice(0, 5).join(', ') + '</li>').join('')}</ul>
      <p style="color:#888;font-size:11px;margin-top:24px">Generated by aria-gap-detector-cron @ 6am UTC daily.</p>
    </div>`;
    try {
      await fetch('https://api.resend.com/emails', {
        method: 'POST',
        headers: { 'Authorization': 'Bearer ' + process.env.RESEND_API_KEY, 'Content-Type': 'application/json' },
        body: JSON.stringify({
          from: process.env.RESEND_FROM || 'ARIA <noreply@iisupp.net>',
          to: [process.env.FOUNDER_EMAIL || 'ahmad.wasee@iisupp.net'],
          subject: '[ARIA] ' + out.stubs_drafted + ' KB gap stubs drafted for review',
          html
        })
      });
    } catch {}
  }

  return new Response(JSON.stringify(out), { headers: { 'Content-Type': 'application/json' } });
};
export const config = { schedule: '0 6 * * *' };
